/* ---------- animated stats ---------- */

function Stat({ stat, active }) {
  const value = useCountUp(stat.num, active)
  return (
    <div className="stat">
      <span className="stat-num">
        {value}
        <em>{stat.suffix}</em>
      </span>
      <p>{stat.label}</p>
    </div>
  )
}

export function Stats() {
  const [ref, inView] = useInView()
  return (
    <section className="section-tight" ref={ref}>
      <div className="container">
        <Reveal as="h2" className="h2 center">
          More output. <em>Less production drag.</em>
        </Reveal>
        <div className="stats-row">
          {STATS.map((s) => (
            <Stat key={s.label} stat={s} active={inView} />
          ))}
        </div>
      </div>
    </section>
  )
}

/* ---------- testimonial carousel ---------- */

export function Testimonials() {
  const [index, setIndex] = useState(0)
  const go = (dir) => setIndex((i) => (i + dir + TESTIMONIALS.length) % TESTIMONIALS.length)
  const t = TESTIMONIALS[index]

  return (
    <section className="section-tight">
      <div className="container">
        <Reveal className="tst-card">
          <span className="tst-quote-mark" aria-hidden="true">
            &ldquo;
          </span>
          <blockquote key={index} className="tst-quote">
            {t.quote}
          </blockquote>
          <div className="tst-foot">
            <div className="tst-person" key={`p-${index}`}>
              <span className="tst-avatar">{t.name.charAt(0)}</span>
              <div>
                <strong>{t.name}</strong>
                <span>{t.role}</span>
              </div>
            </div>
            <div className="tst-nav">
              <button aria-label="Previous testimonial" onClick={() => go(-1)}>
                <Icon name="arrow" size={16} className="flip-x" />
              </button>
              <div className="tst-dots">
                {TESTIMONIALS.map((_, i) => (
                  <button
                    key={i}
                    aria-label={`Show testimonial ${i + 1}`}
                    className={i === index ? 'on' : ''}
                    onClick={() => setIndex(i)}
                  />
                ))}
              </div>
              <button aria-label="Next testimonial" onClick={() => go(1)}>
                <Icon name="arrow" size={16} />
              </button>
            </div>
          </div>
        </Reveal>
      </div>
    </section>
  )
}
